const str = prompt("Введите строку: ");
alert(`Ваша строка ${str == "" ? "пустая" : "содержит текст"}`);
const time = +prompt("Введите время в часах: ");
alert(`Ваше время это  ${(time > 6 && time < 10) ? "утро" : (time > 9 && time < 18) ? "день" : (time > 17 && time < 23) ? "вечер" : "ночь"}`);
