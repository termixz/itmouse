var speed = +prompt("Введите скорость своей езды на дороге");
while(speed == null || speed < 0 || speed == undefined){
    alert("Выполнить программу не удалось, попробуйте ввести число");
    var speed = +prompt("Введите скорость своей езды на дороге");
}
if(speed > 60){
    alert(`Вы привесили лимит скорости на дороге! Превышение на ${speed - 60} км/ч`);
} else{
    alert(`Вы ездите безопасно, спасибо!`);
}
